"""Builds lean-travel-data.js: the teleporters and ferries the bot may use, where they stand, and where they go.

Usage: python gen-travel.py <client data folder> [output file]
Reads the client's teleportData.json and npcpos.json (plain or .gz), as served under /assets/data/.
Positions are region-local, as the game sends them. Town world statues are teleport buildings, not NPCs, so they
have no npcpos row; the bot places them from lean-towns-data.js at run time.
"""
import gzip
import json
import sys
from pathlib import Path

folder = Path(sys.argv[1])
out = Path(sys.argv[2]) if len(sys.argv) > 2 else Path(__file__).with_name('lean-travel-data.js')


def load(name):
    for path in (folder / name, folder / (name + '.gz')):
        if path.exists():
            raw = path.read_bytes()
            return json.loads(gzip.decompress(raw) if raw[:2] == b'\x1f\x8b' else raw)
    raise SystemExit('Missing ' + name + ' in ' + str(folder))


teleports = load('teleportData.json')
if teleports.get('format') != 'sro-teleportdata' or teleports.get('version') != 1:
    raise SystemExit('Unexpected teleportData format')
positions = {}
for row in load('npcpos.json')['rows']:
    c = row.split('\t')
    positions.setdefault(int(c[0]), {'regionId': int(c[1]), 'x': round(float(c[2]), 2), 'y': round(float(c[3]), 2), 'z': round(float(c[4]), 2)})

nodes = {}
for r in teleports['teleportRows']:
    if not r['npcRefObjId'] or r['regionId'] & 0x8000:
        continue
    node = {'id': r['id'], 'refObjId': r['npcRefObjId'], 'name': r['nameSymbol']}
    node.update(positions.get(r['npcRefObjId'], {}))
    nodes[r['id']] = node

links = sorted({(l['sourceId'], l['destinationId'], l['fee']) for l in teleports['linkRows']
                if l['sourceId'] != l['destinationId'] and l['sourceId'] in nodes and l['destinationId'] in nodes})
used = {i for link in links for i in link[:2]}
table = {'nodes': [nodes[i] for i in sorted(used)], 'links': [list(link) for link in links]}
out.write_text('// Generated by gen-travel.py from the client\'s teleportData.json and npcpos.json. Do not edit by hand.\n'
               'const TRAVEL_TABLE = ' + json.dumps(table, separators=(',', ':')) + ';\n', encoding='utf-8', newline='\n')
print('Wrote', out, len(table['nodes']), 'teleporters,', len(table['links']), 'links')
