// Generate lean-clipper.js: the game's own movement clipper, for walk-back routing.
//
// Usage: node tools/build-clipper.mjs <OpenSRO checkout>
//
// Reads apps/client-next/src/engine/foundation/navigation/clipper.ts and every
// module it imports at run time from a read-only OpenSRO checkout (the commit the
// live client runs), strips the TypeScript types (Node's own stripper) and wraps
// the modules in one closure, so the userscript gets `NativeClipper.createNavigation()`
// without a bundler. The output is committed; the normal build does not need the
// checkout. Run it again when the game changes its clipper.
//
// The clipper is OpenSRO code (AGPL-3.0-or-later). It is copied unchanged apart
// from type stripping and the module wrapper.
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import { stripTypeScriptTypes } from 'node:module';
import path from 'node:path';

const game = process.argv[2];
if (!game) throw Error('usage: node tools/build-clipper.mjs <OpenSRO checkout>');
const src = path.resolve(game, 'apps/client-next/src');
const ENTRY = 'engine/foundation/navigation/clipper';
const commit = execFileSync('git', ['-C', game, 'log', '-1', '--format=%h %cs'], { encoding: 'utf8' }).trim();

// Module id ('engine/...', no extension) for an import specifier.
const resolve = (spec, from) => {
  const id = spec.startsWith('@/') ? spec.slice(2) : spec.startsWith('.') ? path.posix.join(path.posix.dirname(from), spec) : null;
  if (!id) throw Error(`${from}: unsupported import ${spec}`);
  if (!fs.existsSync(path.join(src, id + '.ts'))) throw Error(`${from}: missing module ${spec}`);
  return id;
};

// Rewrites one stripped module's import and export statements for the closure.
const IMPORT = /^import\s*\{([^}]*)\}\s*from\s*(["'])([^"']+)\2;?[ \t]*$/gm;
const TYPE_ONLY = /^import\s+type\b[\s\S]*?from\s*(["'])[^"']+\1;?[ \t]*$/gm;
function convert(id) {
  const ts = fs.readFileSync(path.join(src, id + '.ts'), 'utf8');
  let code = stripTypeScriptTypes(ts.replace(TYPE_ONLY, ''), { mode: 'transform' });
  const deps = [], names = [];
  code = code.replace(IMPORT, (_, list, quote, spec) => {
    const bindings = list.split(',').map(s => s.trim()).filter(s => s && !s.startsWith('type '));
    if (!bindings.length) return '';
    const dep = resolve(spec, id);
    deps.push(dep);
    return `const { ${bindings.map(b => b.replace(/\s+as\s+/, ': ')).join(', ')} } = need('${dep}');`;
  });
  code = code.replace(/^export\s+(async\s+function|function|const|let|class)\s+([\w$]+)/gm, (_, kind, name) => {
    names.push(name);
    return `${kind} ${name}`;
  });
  code = code.replace(/^export\s*\{([^}]*)\};?[ \t]*$/gm, (_, list) => {
    for (const b of list.split(',').map(s => s.trim()).filter(Boolean)) {
      if (b.startsWith('type ')) continue;
      const [local, as = local] = b.split(/\s+as\s+/);
      names.push(as === local ? local : `${as}: ${local}`);
    }
    return '';
  });
  if (/^\s*(import|export)\b/m.test(code)) throw Error(`${id}: module syntax left after conversion`);
  return { deps, body: `${code.trim()}\nreturn { ${names.join(', ')} };` };
}

// Every module the entry reaches at run time, dependencies first.
const modules = new Map(), order = [];
const visit = (id, stack = []) => {
  if (stack.includes(id)) throw Error('import cycle: ' + [...stack, id].join(' -> '));
  if (modules.has(id)) return;
  const m = convert(id);
  modules.set(id, m);
  for (const dep of m.deps) visit(dep, [...stack, id]);
  order.push(id);
};
visit(ENTRY);

const out = [
  `// lean-clipper.js: GENERATED by tools/build-clipper.mjs from OpenSRO ${commit}. Do not edit.`,
  '// The game\'s own movement clipper (apps/client-next/src/engine/foundation/navigation/clipper.ts',
  `// and the ${order.length - 1} modules it imports), types stripped. OpenSRO code, AGPL-3.0-or-later:`,
  '// https://github.com/opensro-dev/opensro',
  'const NativeClipper = (() => {',
  '  const factories = new Map(), loaded = new Map();',
  '  const need = id => {',
  '    if (!loaded.has(id)) loaded.set(id, factories.get(id)());',
  '    return loaded.get(id);',
  '  };',
  ...order.map(id => `  factories.set('${id}', () => {\n${modules.get(id).body}\n  });`),
  `  return need('${ENTRY}');`,
  '})();',
  ''
].join('\n');
const target = new URL('../lean-clipper.js', import.meta.url);
fs.writeFileSync(target, out.replace(/\r\n/g, '\n'), 'utf8');
console.log(`Wrote lean-clipper.js: ${order.length} modules, ${out.split('\n').length} lines, ${Buffer.byteLength(out)} bytes (OpenSRO ${commit})`);
